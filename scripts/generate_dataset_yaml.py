#!/usr/bin/env python3
"""Generate Ultralytics YOLO dataset.yaml files for KSI-CCTV training.

Phase 8 Track B: 데이터셋 디렉토리 구조를 기반으로 YOLO 학습에 필요한
dataset.yaml 파일을 자동 생성합니다.

Usage:
    python scripts/generate_dataset_yaml.py --dataset-dir data/ppe/yolo --classes person helmet vest
    python scripts/generate_dataset_yaml.py --dataset-dir data/fire_smoke/yolo --classes fire smoke
"""
from __future__ import annotations

import argparse
from pathlib import Path


def generate_dataset_yaml(
    dataset_dir: Path,
    classes: list[str],
    train_ratio: float = 0.8,
    val_ratio: float = 0.1,
) -> Path:
    """Generate dataset.yaml for Ultralytics YOLO training."""
    yaml_path = dataset_dir / "dataset.yaml"

    # Check for split directories
    has_splits = (dataset_dir / "train").exists()

    if has_splits:
        path_str = str(dataset_dir.absolute())
        train_str = "train/images"
        val_str = "val/images"
        test_str = "test/images" if (dataset_dir / "test").exists() else ""
    else:
        # No splits - use the dataset dir directly
        path_str = str(dataset_dir.absolute())
        train_str = "images"
        val_str = "images"
        test_str = ""

    # Build class names section
    names_lines = ["names:"]
    for i, cls in enumerate(classes):
        names_lines.append(f"  {i}: {cls}")

    # Build YAML content
    lines = [
        "# KSI-CCTV Dataset Configuration",
        "# Auto-generated by scripts/generate_dataset_yaml.py",
        "#",
        f"# Classes: {', '.join(classes)}",
        "",
        f"path: {path_str}",
        f"train: {train_str}",
        f"val: {val_str}",
    ]

    if test_str:
        lines.append(f"test: {test_str}")

    lines.extend([
        "",
        *names_lines,
        "",
        "# KSI-CCTV Phase 8 custom model training",
        "# See scripts/download_datasets.py for data sources",
    ])

    yaml_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Generated dataset.yaml: {yaml_path}")
    return yaml_path


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate YOLO dataset.yaml")
    parser.add_argument("--dataset-dir", required=True, type=Path, help="Dataset directory")
    parser.add_argument("--classes", nargs="+", required=True, help="Class names (in order)")
    args = parser.parse_args()

    yaml_path = generate_dataset_yaml(args.dataset_dir, args.classes)
    print("\nDataset config ready for training:")
    print(f"  Path: {yaml_path}")
    print(f"  Classes: {args.classes}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
